#!/usr/bin/env node
/**
 * Sync infra connection settings for native pnpm dev into a gitignored file.
 * Does NOT rewrite apps/api/.env (preserves secrets, comments, and custom overrides).
 */
import { copyFileSync, existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { ensureDockerEnv } from './lib/ensure-docker-env.mjs'
import { buildNativeInfraEnv } from './lib/local-infra-urls.mjs'
import { getRepoRoot } from './lib/docker-env.mjs'

const root = getRepoRoot()
ensureDockerEnv()

const apiEnvPath = path.join(root, 'apps/api/.env')
const apiExample = path.join(root, 'apps/api/.env.example')
const dockerSyncPath = path.join(root, 'apps/api/.env.docker-sync')

if (!existsSync(apiEnvPath) && existsSync(apiExample)) {
  copyFileSync(apiExample, apiEnvPath)
  console.log('Created apps/api/.env from .env.example')
}

const infra = buildNativeInfraEnv()
writeFileSync(
  dockerSyncPath,
  [
    '# Auto-generated — infra ports/credentials from docker/.env (do not edit)',
    '# Regenerated by: pnpm dev, pnpm local:infra, scripts/run-local',
    ...Object.entries(infra).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n')
)

const webEnvPath = path.join(root, 'apps/web/.env.development.local')
const kcPort = new URL(infra.KEYCLOAK_PUBLIC_URL).port || '8180'
writeFileSync(
  webEnvPath,
  [
    '# Auto-generated for native pnpm dev (Vite proxies /api and /auth)',
    `VITE_KEYCLOAK_URL=http://localhost:${kcPort}`,
    'VITE_KEYCLOAK_REALM=Supplify',
    '# Leave VITE_API_URL unset — dev mode uses same-origin + Vite proxy',
    '',
  ].join('\n')
)

const dbPort = new URL(infra.DATABASE_URL.replace(/^postgresql:/, 'http:')).port
console.log(`Native env ready (API → localhost:${dbPort}, credentials from docker/.env)`)
