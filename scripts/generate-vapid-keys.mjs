#!/usr/bin/env node
/**
 * Generate Web Push VAPID keys and write docker/.env.vapid (gitignored).
 *
 * Usage:
 *   pnpm vapid:generate
 *   pnpm vapid:generate -- --email notifications@yourdomain.com
 */
import { writeFileSync, existsSync, readFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const outFile = resolve(root, 'docker/.env.vapid')
const require = createRequire(resolve(root, 'apps/api/package.json'))
const webpush = require('web-push')

function parseEmail(argv) {
  const i = argv.indexOf('--email')
  if (i !== -1 && argv[i + 1]) return argv[i + 1]
  return 'notifications@supplify.local'
}

function main() {
  const email = parseEmail(process.argv.slice(2))
  const keys = webpush.generateVAPIDKeys()
  const body = `# Generated by pnpm vapid:generate — do not commit (gitignored)
VAPID_PUBLIC_KEY=${keys.publicKey}
VAPID_PRIVATE_KEY=${keys.privateKey}
VAPID_EMAIL=${email}
`

  if (existsSync(outFile)) {
    const existing = readFileSync(outFile, 'utf8')
    const hasKeys = /VAPID_PUBLIC_KEY=\S+/m.test(existing) && !/VAPID_PUBLIC_KEY=\s*$/m.test(existing)
    if (hasKeys && !process.argv.includes('--force')) {
      console.log(`Already exists: ${outFile}`)
      console.log('Use --force to overwrite existing keys (invalidates active browser subscriptions).')
      return
    }
  }

  writeFileSync(outFile, body, 'utf8')
  console.log(`Wrote ${outFile}`)
  console.log('\nNext:')
  console.log('  Railway: pnpm railway:vapid:sync -- development')
  console.log('\nPublic key (for verification):')
  console.log(keys.publicKey)
}

main()
